// @assurance 2 canfail:yes — the deferral lines are READ from the spec and the model, and every tracker state is fetched, never typed
// Pending-binding gate (#156) — a deferral is a claim about state this repository cannot see.
//
// The formal model ends every section in a `**Binding:**` line. Three of its forms are self-contained: `realized`
// cites checks that resolve in this tree, `none — <reason>` is judged on its face. `pending — <tracker>` is the
// exception: it points OUTSIDE, so it is the one claim whose truth changes with nobody editing anything here.
//
// Measured 2026-08-13: FIVE of the eight pending bindings named issues that had already closed, the oldest 15 days
// earlier, and two more deferrals sat in prose where no check could see them at all. The only enforcement that
// existed was in `model-domain-totality.mjs`: `if (kind === 'pending' && reason.length < 3)`. The reference had to
// be three characters long. `pending — #106` would have passed forever.
//
// It fails in BOTH directions and neither is visible from inside the document. Work that shipped leaves the model
// understating its own realization, with the citations that would prove it never written. Work that did not ship
// leaves an obligation with no owner, still reading as owned.
//
// So this gate resolves the reference. Two legs, because there are two ways a deferral escapes:
//   1. every `**Binding: pending — …#N…**` names an OPEN issue;
//   2. no deferral-flavoured line carries a tracker reference OUTSIDE the marker — a deferral written as prose is
//      invisible to leg 1, which is exactly how the front matter said "reporting side pending, #138" for nine days
//      after #138 closed.
//
// FAIL-CLOSED on an unreachable tracker. A gate whose whole job is resolving a reference may not pass when it
// could not resolve one; "the API was down" and "the reference is good" must never share an exit code.
import { readFileSync, writeFileSync } from 'node:fs';

const REPO = 'thelabmd/UST-Protocol';
const STATE_PATH = new URL('./tracker-state.json', import.meta.url);
const SOURCES = ['../spec/UST-1.0-formal-model.md', '../spec/UST-1.0.md'];

// A deferral SAYS it is one. The set is closed and small on purpose: a wide net would flag provenance
// ("fixed in #75"), which legitimately points at a closed issue and is most of the references in the tree.
const DEFER = /\b(pending|not yet realized|remains open|unrealized|still owed)\b/i;
const MARKER = /\*\*Binding:\s*pending\s*—/;
// A deferral line qualifies its FIRST reference and then continues in shorthand — `#137 (the report) and #138
// (the ruleset term)`. Reading only the qualified form measured 6 of the 7 live failures and silently dropped
// #138 from two lines: the scanner named a sample of its own subject, which is the defect this gate is about.
// On a line that already declares itself a deferral, every `#N` on it belongs to the deferral.
const REF = /(?:(?:thelabmd\/)?UST-Protocol)?#(\d+)/g;

const lines = [];
for (const rel of SOURCES) {
  const name = rel.split('/').pop();
  readFileSync(new URL(rel, import.meta.url), 'utf8').split('\n').forEach((l, i) => {
    if (!/UST-Protocol#\d+/.test(l) || !DEFER.test(l)) return;
    // The TARGET of a deferral is what stands inside the marker's own `**…**` span. A binding line may also
    // NARRATE — «#137 and #138 both closed on … and this line named them for a week» — and those references are
    // history, not deferral. Reading the whole line made a line explaining why it moved fail for saying so, which
    // is a gate that punishes the record of its own finding.
    const span = /\*\*Binding:\s*pending\s*—[^*]*\*\*/.exec(l);
    const scope = span ? span[0] : l;
    lines.push({ name, no: i + 1, text: l, marker: MARKER.test(l), refs: [...scope.matchAll(REF)].map((m) => m[1]) });
  });
}

if (process.argv.includes('--write')) {
  const token = process.env.GITHUB_TOKEN || process.env.GH_TOKEN;
  const want = [...new Set(lines.flatMap((l) => l.refs))].sort((a, b) => a - b);
  const out = {};
  for (const n of want) {
    const r = await fetch(`https://api.github.com/repos/${REPO}/issues/${n}`, {
      headers: { accept: 'application/vnd.github+json', ...(token ? { authorization: 'Bearer ' + token } : {}) },
      signal: AbortSignal.timeout(15000),
    });
    // `fetch` does not throw on 4xx/5xx. An unread tracker must stop the write, never write a guess.
    if (!r.ok) { console.error(`  ✗ tracker unreachable for #${n}: HTTP ${r.status} — refusing to write a state nobody read`); process.exit(1); }
    const j = await r.json();
    out[n] = { state: String(j.state || '').toUpperCase(), closed_at: j.closed_at ?? null };
  }
  writeFileSync(STATE_PATH, JSON.stringify({ _: `resolved from ${REPO} — regenerated by \`--write\`, never typed`, repo: REPO, issues: out }, null, 1) + '\n');
  console.log(`  wrote tracker state for ${want.length} referenced issue(s)`);
  process.exit(0);
}

let pass = 0; const fail = [];
const check = (ok, msg) => { if (ok) pass++; else fail.push(msg); };

// vacuity: a scanner that finds nothing passes everything. The count is pinned LOW, not exact — new deferrals are
// ordinary, losing them all is not.
check(lines.length >= 4, `only ${lines.length} deferral line(s) found across the spec and the model — the scanner has lost its subject and every leg below would be vacuous`);

let STATE;
try { STATE = JSON.parse(readFileSync(STATE_PATH, 'utf8')).issues; }
catch { STATE = null; }
check(!!STATE, 'tools/tracker-state.json is missing or unreadable — run `node tools/pending-binding-gate.mjs --write`');

for (const l of STATE ? lines : []) {
  // leg 2 first: a prose deferral is not merely unresolved, it is unresolvABLE, so it is its own failure.
  if (!l.marker) {
    fail.push(`${l.name}:${l.no} defers to ${l.refs.map((r) => '#' + r).join(', ')} in PROSE — a deferral outside the \`**Binding: pending — …**\` form is invisible to the check that resolves it. Move it into the marker, or drop the tracker reference: «${l.text.trim().slice(0, 90)}»`);
    continue;
  }
  // Scoping the target to the marker span (above) opened this hole and it is closed here: a marker whose span
  // names NO tracker would loop over nothing and pass. `pending` with the reference pushed outside the `**…**`
  // is `pending` with no tracker at all.
  if (!l.refs.length) {
    fail.push(`${l.name}:${l.no} is \`pending\` and names no tracker INSIDE the marker — a reference after the closing \`**\` is narrative, not a deferral target: «${l.text.trim().slice(0, 90)}»`);
    continue;
  }
  // leg 1: the reference must resolve, and it must be OPEN.
  for (const n of l.refs) {
    const s = STATE[n];
    if (!s) { fail.push(`${l.name}:${l.no} defers to #${n}, which is absent from the tracker state — regenerate with \`--write\``); continue; }
    if (s.state !== 'OPEN') {
      const days = s.closed_at ? Math.floor((Date.parse(new Date().toISOString()) - Date.parse(s.closed_at)) / 86400000) : '?';
      fail.push(`${l.name}:${l.no} is \`pending\` on #${n}, CLOSED ${days} day(s) ago — closing an issue does not discharge an obligation. Move the line to \`realized\` WITH citations if the work shipped, or to a tracker that is open if it did not; do not assume which.`);
    } else pass++;
  }
}

console.log(`\n  pending bindings   PASS ${pass}   FAIL ${fail.length}   (${lines.length} deferral line(s): ${lines.filter((l) => l.marker).length} marker, ${lines.filter((l) => !l.marker).length} prose)`);
if (fail.length) { fail.forEach((f) => console.log('    ✗ ' + f)); process.exit(1); }
console.log('  ✓ every deferral is written in the resolvable form and names a tracker that is still open');
